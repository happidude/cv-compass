-- Additive OCR foundation. NULL profile identifies untouched legacy jobs/extractions.
ALTER TABLE "CV_PROCESSING_JOBS"
    ADD COLUMN "PROFILE_REVISION" VARCHAR(128),
    ADD COLUMN "GENERATION" INTEGER,
    ADD COLUMN "MAX_ATTEMPTS" INTEGER,
    ADD COLUMN "ATTEMPTS_STARTED" INTEGER,
    ADD COLUMN "NEXT_ATTEMPT_AT" TIMESTAMPTZ,
    ADD COLUMN "CURRENT_ATTEMPT_ID" BIGINT,
    ADD COLUMN "ADMISSION_SNAPSHOT" JSONB,
    ADD COLUMN "END_REASON" VARCHAR(40),
    ADD COLUMN "ERROR_CODE" VARCHAR(60);
ALTER TABLE "CV_PROCESSING_JOBS" DROP CONSTRAINT "CK_JOB_STATUS";
ALTER TABLE "CV_PROCESSING_JOBS" ADD CONSTRAINT "CK_JOB_STATUS"
    CHECK ("STATUS" IN ('PENDING','PROCESSING','COMPLETED','PARTIAL','FAILED'));
ALTER TABLE "CV_DOCUMENTS" DROP CONSTRAINT "CK_DOCUMENT_STATUS";
ALTER TABLE "CV_DOCUMENTS" ADD CONSTRAINT "CK_DOCUMENT_STATUS"
    CHECK ("STATUS" IN ('PENDING','PROCESSING','COMPLETED','PARTIAL','FAILED'));
ALTER TABLE "CV_PROCESSING_JOBS" ADD CONSTRAINT "CK_OCR_JOB_FIELDS" CHECK (
    "PROFILE_REVISION" IS NULL OR (
        length("PROFILE_REVISION") BETWEEN 1 AND 128 AND
        "GENERATION" IS NOT NULL AND "GENERATION">0 AND
        "MAX_ATTEMPTS" IS NOT NULL AND "MAX_ATTEMPTS" BETWEEN 1 AND 3 AND
        "ATTEMPTS_STARTED" IS NOT NULL AND "ATTEMPTS_STARTED" BETWEEN 0 AND "MAX_ATTEMPTS" AND
        "RETRY_COUNT"=GREATEST("ATTEMPTS_STARTED"-1,0) AND
        "NEXT_ATTEMPT_AT" IS NOT NULL AND "ADMISSION_SNAPSHOT" IS NOT NULL AND
        jsonb_typeof("ADMISSION_SNAPSHOT")='object' AND
        ("STATUS"<>'PROCESSING' OR "CURRENT_ATTEMPT_ID" IS NOT NULL) AND
        ("STATUS" NOT IN ('COMPLETED','PARTIAL','FAILED') OR
            ("END_REASON" IS NOT NULL AND "COMPLETED_AT" IS NOT NULL))));
ALTER TABLE "CV_PROCESSING_JOBS" ADD CONSTRAINT "CK_OCR_JOB_END_REASON" CHECK (
    "END_REASON" IS NULL OR "END_REASON" IN
    ('RESULT_SUCCESS','RESULT_PARTIAL','OCR_FAILED','INFRA_FAILURE','RETRIES_EXHAUSTED','CONFIGURATION_ERROR'));
CREATE UNIQUE INDEX "UQ_OCR_JOB_GENERATION" ON "CV_PROCESSING_JOBS"
    ("CV_DOCUMENT_ID","PROFILE_REVISION","GENERATION") WHERE "PROFILE_REVISION" IS NOT NULL;
-- All profiles share the document status projection; only one new-protocol active job/document.
CREATE UNIQUE INDEX "UQ_OCR_ACTIVE_DOCUMENT" ON "CV_PROCESSING_JOBS" ("CV_DOCUMENT_ID")
    WHERE "PROFILE_REVISION" IS NOT NULL AND "STATUS" IN ('PENDING','PROCESSING');
CREATE INDEX "IX_OCR_JOB_READY" ON "CV_PROCESSING_JOBS" ("PROFILE_REVISION","NEXT_ATTEMPT_AT","ID")
    WHERE "STATUS"='PENDING' AND "PROFILE_REVISION" IS NOT NULL;

CREATE TABLE "CV_OCR_ATTEMPTS" (
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "PUBLIC_ID" UUID NOT NULL,
    "JOB_ID" BIGINT NOT NULL,
    "ATTEMPT_NO" INTEGER NOT NULL,
    "WORKER_ID" VARCHAR(128) NOT NULL,
    "CLAIM_REQUEST_ID" UUID NOT NULL,
    "CLAIM_BODY_SHA256" CHAR(64) NOT NULL,
    "LEASE_TOKEN_HASH" CHAR(64) NOT NULL,
    "LEASE_EXPIRES_AT" TIMESTAMPTZ NOT NULL,
    "HARD_DEADLINE_AT" TIMESTAMPTZ NOT NULL,
    "RECLAIM_AFTER" TIMESTAMPTZ NOT NULL,
    "STATUS" VARCHAR(20) NOT NULL,
    "STARTED_AT" TIMESTAMPTZ NOT NULL,
    "FINISHED_AT" TIMESTAMPTZ,
    "END_REASON" VARCHAR(40),
    "ERROR_CODE" VARCHAR(60),
    "OUTCOME_SHA256" CHAR(64),
    CONSTRAINT "PK_CV_OCR_ATTEMPTS" PRIMARY KEY ("ID"),
    CONSTRAINT "UQ_OCR_ATTEMPT_PUBLIC" UNIQUE ("PUBLIC_ID"),
    CONSTRAINT "FK_OCR_ATTEMPT_JOB" FOREIGN KEY ("JOB_ID") REFERENCES "CV_PROCESSING_JOBS" ("ID"),
    CONSTRAINT "UQ_OCR_ATTEMPT_NUMBER" UNIQUE ("JOB_ID","ATTEMPT_NO"),
    CONSTRAINT "UQ_OCR_CLAIM" UNIQUE ("WORKER_ID","CLAIM_REQUEST_ID"),
    CONSTRAINT "UQ_OCR_ATTEMPT_JOB" UNIQUE ("ID","JOB_ID"),
    CONSTRAINT "CK_OCR_ATTEMPT_NO" CHECK ("ATTEMPT_NO" BETWEEN 1 AND 3),
    CONSTRAINT "CK_OCR_ATTEMPT_WORKER" CHECK ("WORKER_ID" ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$'),
    CONSTRAINT "CK_OCR_ATTEMPT_HASHES" CHECK (
        "CLAIM_BODY_SHA256"::TEXT ~ '^[0-9a-f]{64}$' AND "LEASE_TOKEN_HASH"::TEXT ~ '^[0-9a-f]{64}$' AND
        ("OUTCOME_SHA256" IS NULL OR "OUTCOME_SHA256"::TEXT ~ '^[0-9a-f]{64}$')),
    CONSTRAINT "CK_OCR_ATTEMPT_TIMES" CHECK (
        "STARTED_AT"<"LEASE_EXPIRES_AT" AND "LEASE_EXPIRES_AT"<="HARD_DEADLINE_AT" AND
        "HARD_DEADLINE_AT"<"RECLAIM_AFTER" AND ("FINISHED_AT" IS NULL OR "FINISHED_AT">="STARTED_AT")),
    CONSTRAINT "CK_OCR_ATTEMPT_STATUS" CHECK ("STATUS" IN ('ACTIVE','EXPIRED','FAILED','ACCEPTED')),
    CONSTRAINT "CK_OCR_ATTEMPT_END" CHECK (
        ("STATUS"='ACTIVE' AND "FINISHED_AT" IS NULL AND "END_REASON" IS NULL AND "OUTCOME_SHA256" IS NULL) OR
        ("STATUS" IN ('FAILED','ACCEPTED') AND "FINISHED_AT" IS NOT NULL AND "END_REASON" IS NOT NULL AND "OUTCOME_SHA256" IS NOT NULL) OR
        ("STATUS"='EXPIRED' AND "FINISHED_AT" IS NOT NULL AND "END_REASON" IS NOT NULL AND "END_REASON"='LEASE_EXPIRED' AND "OUTCOME_SHA256" IS NULL)),
    CONSTRAINT "CK_OCR_ATTEMPT_END_REASON" CHECK ("END_REASON" IS NULL OR "END_REASON" IN
        ('RESULT_SUCCESS','RESULT_PARTIAL','OCR_FAILED','INFRA_FAILURE','RETRIES_EXHAUSTED','CONFIGURATION_ERROR','LEASE_EXPIRED'))
);
CREATE UNIQUE INDEX "UQ_OCR_ACTIVE_ATTEMPT" ON "CV_OCR_ATTEMPTS" ("JOB_ID") WHERE "STATUS"='ACTIVE';
CREATE INDEX "IX_OCR_ATTEMPT_EXPIRY" ON "CV_OCR_ATTEMPTS" ("LEASE_EXPIRES_AT","JOB_ID") WHERE "STATUS"='ACTIVE';
ALTER TABLE "CV_PROCESSING_JOBS" ADD CONSTRAINT "FK_OCR_CURRENT_ATTEMPT"
    FOREIGN KEY ("CURRENT_ATTEMPT_ID","ID") REFERENCES "CV_OCR_ATTEMPTS" ("ID","JOB_ID");

ALTER TABLE "CV_EXTRACTIONS"
    ADD COLUMN "ATTEMPT_ID" BIGINT,
    ADD COLUMN "OCR_RESULT" JSONB,
    ADD COLUMN "OCR_STATUS" VARCHAR(20),
    ADD COLUMN "PROFILE_REVISION" VARCHAR(128),
    ADD COLUMN "PROVENANCE" JSONB,
    ADD CONSTRAINT "FK_EXTRACTION_ATTEMPT_JOB" FOREIGN KEY ("ATTEMPT_ID","PROCESSING_JOB_ID")
        REFERENCES "CV_OCR_ATTEMPTS" ("ID","JOB_ID"),
    ADD CONSTRAINT "UQ_EXTRACTION_ATTEMPT" UNIQUE ("ATTEMPT_ID"),
    ADD CONSTRAINT "CK_OCR_EXTRACTION_FIELDS" CHECK (
        ("OCR_RESULT" IS NULL AND "ATTEMPT_ID" IS NULL AND "OCR_STATUS" IS NULL AND "PROFILE_REVISION" IS NULL AND "PROVENANCE" IS NULL) OR
        ("OCR_RESULT" IS NOT NULL AND "ATTEMPT_ID" IS NOT NULL AND "OCR_STATUS" IS NOT NULL AND
         "PROFILE_REVISION" IS NOT NULL AND "PROVENANCE" IS NOT NULL AND
         jsonb_typeof("OCR_RESULT")='object' AND "OCR_RESULT" ?& ARRAY['pages','status'] AND
         jsonb_typeof("OCR_RESULT"->'pages')='array' AND jsonb_typeof("OCR_RESULT"->'status')='string' AND
         jsonb_typeof("PROVENANCE")='object' AND "OCR_STATUS" IN ('success','partial','failed') AND
         "OCR_RESULT"->>'status'="OCR_STATUS" AND "STRUCTURED_DATA" IS NULL AND "RAW_TEXT" IS NULL));
ALTER TABLE "CV_EXTRACTIONS" DROP CONSTRAINT "CK_EXTRACTION_METHOD";
ALTER TABLE "CV_EXTRACTIONS" ADD CONSTRAINT "CK_EXTRACTION_METHOD"
    CHECK ("EXTRACTION_METHOD" IN ('TEXT_EXTRACTION','OCR','MIXED','NONE'));
CREATE UNIQUE INDEX "UQ_OCR_EXTRACTION_JOB" ON "CV_EXTRACTIONS" ("PROCESSING_JOB_ID") WHERE "OCR_RESULT" IS NOT NULL;
