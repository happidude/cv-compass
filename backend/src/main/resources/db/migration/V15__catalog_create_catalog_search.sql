    ADD "SCOPE_CODE" varchar(64),
    ADD "NORMALIZATION_ORIGIN" varchar(8) CHECK ("NORMALIZATION_ORIGIN" IN ('AI', 'USER')),
    ADD FOREIGN KEY ("COMPANY_ID", "COMPANY_KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND"),
    ADD FOREIGN KEY ("TITLE_ID", "TITLE_KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND");
CREATE INDEX "IDX_EXPERIENCES_COMPANY_ID" ON "CANDIDATE"."EXPERIENCES" ("COMPANY_ID");
CREATE INDEX "IDX_EXPERIENCES_TITLE_ID" ON "CANDIDATE"."EXPERIENCES" ("TITLE_ID");

ALTER TABLE "CANDIDATE"."PROFILES"
    ADD "LOCATION_PROVINCE" varchar(64),
    ADD "TOTAL_EXPERIENCE_MONTHS" integer CHECK ("TOTAL_EXPERIENCE_MONTHS" >= 0),
    ADD "CURRENT_COMPANY_ID" bigint,
    ADD "CURRENT_COMPANY_KIND" varchar(8) GENERATED ALWAYS AS (CASE WHEN "CURRENT_COMPANY_ID" IS NULL THEN NULL ELSE 'COMPANY' END) STORED,
    ADD "CURRENT_TITLE_ID" bigint,
    ADD "CURRENT_TITLE_KIND" varchar(8) GENERATED ALWAYS AS (CASE WHEN "CURRENT_TITLE_ID" IS NULL THEN NULL ELSE 'TITLE' END) STORED,
    ADD FOREIGN KEY ("CURRENT_COMPANY_ID", "CURRENT_COMPANY_KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND"),
    ADD FOREIGN KEY ("CURRENT_TITLE_ID", "CURRENT_TITLE_KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND");

