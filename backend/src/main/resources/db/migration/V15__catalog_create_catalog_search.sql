CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE SCHEMA "CATALOG";
CREATE SCHEMA "SEARCH";

CREATE TABLE "CATALOG"."TAXONOMY_CODES" (
    "KIND" varchar(16) NOT NULL CHECK ("KIND" IN ('FUNCTION', 'SENIORITY', 'INDUSTRY', 'SCOPE')),
    "CODE" varchar(64) NOT NULL,
    "LABEL_VI" text NOT NULL,
    "TAXONOMY_VERSION" varchar(32) NOT NULL,
    "ACTIVE" boolean NOT NULL DEFAULT true,
    PRIMARY KEY ("KIND", "CODE")
);

CREATE TABLE "CATALOG"."ENTRIES" (
    "ID" bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "KIND" varchar(8) NOT NULL CHECK ("KIND" IN ('COMPANY', 'TITLE')),
    "NAME" text NOT NULL CHECK ("NAME" ~ '[^[:space:]]'),
    "NAME_FOLDED" text NOT NULL,
    "PARENT_ID" bigint,
    "PARENT_KIND" varchar(8) GENERATED ALWAYS AS (CASE WHEN "PARENT_ID" IS NULL THEN NULL ELSE 'COMPANY' END) STORED,
    "INDUSTRY_CODE" varchar(64),
    "FUNCTION_CODES" text[],
    "SENIORITY_CODE" varchar(64),
    "SCOPE_CODE" varchar(64),
    "PROPOSED_LABEL" text,
    "ORIGIN" varchar(8) NOT NULL CHECK ("ORIGIN" IN ('SEED', 'AI', 'USER')),
    "CREATED_AT" timestamptz NOT NULL DEFAULT now(),
    "UPDATED_AT" timestamptz NOT NULL DEFAULT now(),
    UNIQUE ("KIND", "NAME_FOLDED"),
    UNIQUE ("ID", "KIND"),
    FOREIGN KEY ("PARENT_ID", "PARENT_KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND"),
    CHECK ("PARENT_ID" <> "ID"),
    CHECK ("KIND" <> 'COMPANY' OR ("FUNCTION_CODES" IS NULL AND "SENIORITY_CODE" IS NULL AND "SCOPE_CODE" IS NULL)),
    CHECK ("KIND" <> 'TITLE' OR ("PARENT_ID" IS NULL AND "INDUSTRY_CODE" IS NULL AND "FUNCTION_CODES" IS NOT NULL
        AND cardinality("FUNCTION_CODES") BETWEEN 1 AND 2 AND "SENIORITY_CODE" IS NOT NULL)),
    CHECK (NOT COALESCE("INDUSTRY_CODE" = 'OTHER' OR 'OTHER' = ANY("FUNCTION_CODES"), false)
        OR COALESCE("PROPOSED_LABEL" ~ '[^[:space:]]', false))
);
CREATE INDEX "IDX_ENTRIES_PARENT_ID" ON "CATALOG"."ENTRIES" ("PARENT_ID");

CREATE TABLE "CATALOG"."ALIASES" (
    "ID" bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "KIND" varchar(8) NOT NULL CHECK ("KIND" IN ('COMPANY', 'TITLE')),
    "ALIAS_FOLDED" text NOT NULL,
    "ENTRY_ID" bigint NOT NULL,
    "ALIAS_RAW" text NOT NULL,
    "ORIGIN" varchar(8) NOT NULL CHECK ("ORIGIN" IN ('SEED', 'AI', 'USER')),
    UNIQUE ("KIND", "ALIAS_FOLDED"),
    FOREIGN KEY ("ENTRY_ID", "KIND") REFERENCES "CATALOG"."ENTRIES" ("ID", "KIND") ON DELETE CASCADE
);
CREATE INDEX "IDX_ALIASES_ENTRY_ID" ON "CATALOG"."ALIASES" ("ENTRY_ID");

ALTER TABLE "CANDIDATE"."EXPERIENCES"
    ADD "COMPANY_ID" bigint,
    ADD "COMPANY_KIND" varchar(8) GENERATED ALWAYS AS (CASE WHEN "COMPANY_ID" IS NULL THEN NULL ELSE 'COMPANY' END) STORED,
    ADD "TITLE_ID" bigint,
