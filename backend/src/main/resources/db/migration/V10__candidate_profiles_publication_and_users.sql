CREATE TABLE "CV_USERS" (
 "USERNAME" VARCHAR(100) PRIMARY KEY, "PASSWORD_HASH" VARCHAR(100) NOT NULL,
 "ROLE" VARCHAR(5) NOT NULL CHECK("ROLE" IN ('USER','ADMIN')),
 "ENABLED" BOOLEAN NOT NULL DEFAULT true
);
