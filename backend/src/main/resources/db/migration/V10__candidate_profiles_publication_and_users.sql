-- Candidate owns profiles/review/history; ingestion retains the single legacy identity entity.
CREATE TABLE "CANDIDATE_PROFILES" (
 "CANDIDATE_ID" BIGINT PRIMARY KEY REFERENCES "CANDIDATES"("ID"),
 "VERSION" BIGINT NOT NULL DEFAULT 0 CHECK ("VERSION">=0),
 "FULL_NAME" VARCHAR(255), "EMAIL" VARCHAR(255), "PHONE" VARCHAR(50), "LOCATION" VARCHAR(255), "SUMMARY" TEXT,
 "BASIC" JSONB NOT NULL DEFAULT '{}' CHECK(jsonb_typeof("BASIC")='object'),
 "BASIC_STATE" VARCHAR(16) NOT NULL DEFAULT 'UNVERIFIED' CHECK("BASIC_STATE" IN ('UNVERIFIED','CONFIRMED','EDITED')),
 "BASIC_ORIGIN" VARCHAR(8) NOT NULL DEFAULT 'MAPPING' CHECK("BASIC_ORIGIN" IN ('MAPPING','USER')),
 "EXTENSIONS" JSONB NOT NULL DEFAULT '{"schemaVersion":1,"issues":[]}',
 "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "UPDATED_AT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "CANDIDATE_EXPERIENCES" (
 "ID" UUID PRIMARY KEY,
 "CANDIDATE_ID" BIGINT NOT NULL REFERENCES "CANDIDATE_PROFILES"("CANDIDATE_ID"),
 "COMPANY_RAW" TEXT, "COMPANY_NORMALIZED" TEXT, "TITLE_RAW" TEXT,
 "START_DATE" DATE, "START_PRECISION" VARCHAR(5), "END_DATE" DATE, "END_PRECISION" VARCHAR(5),
 "ONGOING_AS_STATED" BOOLEAN NOT NULL DEFAULT false,
 "FUNCTION_CODES" JSONB NOT NULL DEFAULT '[]', "INDUSTRY_CODES" JSONB NOT NULL DEFAULT '[]',
 "SENIORITY_CODE" VARCHAR(64), "DESCRIPTION_RAW" TEXT,
 "DATA" JSONB NOT NULL CHECK(jsonb_typeof("DATA")='object'),
 "DATA_SCHEMA_VERSION" INTEGER NOT NULL DEFAULT 1 CHECK("DATA_SCHEMA_VERSION"=1),
 "STATE" VARCHAR(16) NOT NULL CHECK("STATE" IN ('UNVERIFIED','CONFIRMED','EDITED')),
 "ORIGIN" VARCHAR(8) NOT NULL CHECK("ORIGIN" IN ('MAPPING','USER')),
 "DOCUMENT_ID" BIGINT REFERENCES "CV_DOCUMENTS"("ID"),
 "RESULT_ID" BIGINT REFERENCES "CV_MAPPING_RESULTS"("ID"),
 "DELETED" BOOLEAN NOT NULL DEFAULT false,
 CHECK("START_PRECISION" IS NULL OR "START_PRECISION" IN ('YEAR','MONTH','DAY')),
 CHECK("END_PRECISION" IS NULL OR "END_PRECISION" IN ('YEAR','MONTH','DAY'))
);
CREATE INDEX "IX_CANDIDATE_EXPERIENCES" ON "CANDIDATE_EXPERIENCES"("CANDIDATE_ID");
CREATE TABLE "CANDIDATE_PUBLICATIONS" (
 "RESULT_ID" BIGINT PRIMARY KEY REFERENCES "CV_MAPPING_RESULTS"("ID"),
 "CANDIDATE_ID" BIGINT REFERENCES "CANDIDATE_PROFILES"("CANDIDATE_ID"),
 "DOCUMENT_ID" BIGINT NOT NULL REFERENCES "CV_DOCUMENTS"("ID"),
 "EXTRACTION_ID" BIGINT NOT NULL, "CONFIG_ID" BIGINT NOT NULL,
 "STATUS" VARCHAR(20) NOT NULL CHECK("STATUS" IN ('PUBLISHED','PROPOSED','SUPERSEDED','SKIPPED')),
 "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "IX_CANDIDATE_PUBLICATION_DOCUMENT" ON "CANDIDATE_PUBLICATIONS"("DOCUMENT_ID","EXTRACTION_ID" DESC,"CONFIG_ID" DESC,"RESULT_ID" DESC);
CREATE TABLE "CANDIDATE_PROPOSALS" (
 "ID" UUID PRIMARY KEY,
 "CANDIDATE_ID" BIGINT NOT NULL REFERENCES "CANDIDATE_PROFILES"("CANDIDATE_ID"),
 "RESULT_ID" BIGINT NOT NULL REFERENCES "CANDIDATE_PUBLICATIONS"("RESULT_ID"),
 "DOCUMENT_ID" BIGINT NOT NULL REFERENCES "CV_DOCUMENTS"("ID"),
 "DATA" JSONB NOT NULL,
 "STATUS" VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK("STATUS" IN ('OPEN','ACCEPTED','REJECTED')),
 "DECIDED_BY" VARCHAR(100), "DECIDED_AT" TIMESTAMPTZ
);
CREATE INDEX "IX_CANDIDATE_PROPOSALS" ON "CANDIDATE_PROPOSALS"("CANDIDATE_ID","STATUS");
CREATE TABLE "CANDIDATE_HISTORY" (
 "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 "CANDIDATE_ID" BIGINT NOT NULL REFERENCES "CANDIDATE_PROFILES"("CANDIDATE_ID"),
 "VERSION" BIGINT NOT NULL, "ACTOR" VARCHAR(100) NOT NULL,
 "ACTION" VARCHAR(40) NOT NULL, "BEFORE" JSONB, "AFTER" JSONB,
 "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE("CANDIDATE_ID","VERSION")
);
CREATE TABLE "CANDIDATE_PUBLICATION_SETTINGS" ("ID" INTEGER PRIMARY KEY CHECK("ID"=1),"AFTER_ID" BIGINT NOT NULL DEFAULT 0 CHECK("AFTER_ID">=0),"UPPER_ID" BIGINT CHECK("UPPER_ID">=0));
